"""Writes ios/App/Journal/VocabularyLabels.swift from the Android app's
label table (android/.../journal/Labels.kt, LABELS) and its English strings
(android/app/src/main/res/values/strings.xml), so both apps name the core's
vocabulary the same way.

Usage: ios/scripts/labels-from-android.py [--check]
  --check: fail if the Swift file isn't what this would write.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LABELS_KT = ROOT / "android/app/src/main/kotlin/app/terpoir/journal/Labels.kt"
STRINGS = ROOT / "android/app/src/main/res/values/strings.xml"
OUT = ROOT / "ios/App/Journal/VocabularyLabels.swift"

HEADER = """// SPDX-License-Identifier: GPL-3.0-or-later WITH AdditionRef-Terpoir-AppStore-exception
// Copyright (C) 2026 The Terpoir Authors
// See LICENSING.md for the additional permission under GPLv3 section 7.

// Generated by ios/scripts/labels-from-android.py from the Android app's
// label table and strings. Don't edit; change Android's and run it again.

/// Display names for the core's vocabulary slugs, as the Android app shows them.
let vocabularyLabels: [String: String] = [
"""


def android_string(element: ET.Element) -> str:
    """An Android string resource's text, unescaped."""
    text = "".join(element.itertext())
    text = re.sub(r"\\(['\"@?])", r"\1", text)
    return text.replace("\\n", "\n")


def swift_literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def generate() -> str:
    table = LABELS_KT.read_text(encoding="utf-8")
    block = table[table.index("private val LABELS"):]
    block = block[: block.index("\n)")]
    pairs = re.findall(r'"([a-z0-9_]+)" to R\.string\.([a-z0-9_]+)', block)
    strings = {
        e.get("name"): android_string(e) for e in ET.parse(STRINGS).getroot().iter("string")
    }
    labels = {}
    for slug, name in pairs:
        if name not in strings:
            sys.exit(f"labels-from-android: no string {name} for {slug}")
        labels[slug] = strings[name]
    lines = [f"    {swift_literal(slug)}: {swift_literal(text)}," for slug, text in sorted(labels.items())]
    return HEADER + "\n".join(lines) + "\n]\n"


def main() -> None:
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit("VocabularyLabels.swift is out of date: run ios/scripts/labels-from-android.py")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({text.count(chr(10)) - HEADER.count(chr(10)) - 1} labels)")


if __name__ == "__main__":
    main()
