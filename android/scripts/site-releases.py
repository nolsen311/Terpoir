# has SBOMs, and PUBLISHED (its publication date). Newest first. Static
# HTML, like the rest of the site: no scripts, no external requests.
# Python 3 standard library only. Run from the repository root.

import html
import pathlib
import re

SITE = pathlib.Path("site/releases")
REPO = "https://github.com/nolsen311/Terpoir"


def version_key(tag: str) -> tuple:
    return tuple(int(p) for p in re.findall(r"\d+", tag))


def sums(path: pathlib.Path) -> list[tuple[str, str]]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            digest, name = line.split(maxsplit=1)
            rows.append((digest, name.lstrip("*")))
    return rows


def release(folder: pathlib.Path) -> str:
    tag = folder.name
    date = (folder / "PUBLISHED").read_text(encoding="utf-8").strip()
    files = "".join(
        f'<dt>{html.escape(name)}</dt><dd>{html.escape(digest)}</dd>'
        for digest, name in sums(folder / "SHA256SUMS")
    )
    links = [
        f'<a href="/releases/{tag}/SHA256SUMS">SHA256SUMS</a>',
        f'<a href="/releases/{tag}/SHA256SUMS.sig">SHA256SUMS.sig</a>',
    ]
    if (folder / "SBOM-SHA256SUMS").exists():
        links.append(f'<a href="/releases/{tag}/SBOM-SHA256SUMS">SBOM-SHA256SUMS</a>')
    links.append(f'<a href="{REPO}/releases/tag/{tag}">release on GitHub</a>')
    return (
        f'  <section id="{tag}">\n'
        f'    <h2>{html.escape(tag)} <span class="meta">{html.escape(date)}</span></h2>\n'
        f"    <dl>{files}</dl>\n"
        f'    <p class="links">{" · ".join(links)}</p>\n'
        f"  </section>\n"
    )


def main() -> None:
    folders = sorted(
        (p for p in SITE.iterdir() if p.is_dir() and p.name.startswith("v")),
        key=lambda p: version_key(p.name),
        reverse=True,
    )
    body = "".join(release(f) for f in folders)
    page = PAGE.replace("@@RELEASES@@", body)
    (SITE / "index.html").write_text(page, encoding="utf-8")


