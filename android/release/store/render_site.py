#   app/src/main/res/font/fraunces.ttf
# Needs Pillow and fontTools. Run render.py first: the favicon PNGs are
# scaled from its icon-512.png.
#
# Writes the website's logo and favicons from the same shapes as the app
# icon and the Play graphics:
#   logo.svg              the feature graphic's lockup (the open journal on
#                         the wordmark's baseline, bubbles above, "Terpoir"
#                         in Fraunces as outlines, so the site loads no
#                         font), ink coloured for light and dark pages
#   favicon.svg           the app icon on its background, rounded
#   favicon.ico           16, 32 and 48 px, for browsers that ask for it
#   apple-touch-icon.png  180 px
import re
import sys
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image

HEADER = """<!-- SPDX-License-Identifier: GPL-3.0-or-later WITH AdditionRef-Terpoir-AppStore-exception -->
<!-- Copyright (C) 2026 The Terpoir Authors -->
<!-- Generated by android/release/store/render_site.py; edit that, not this. -->
"""
# ic_launcher_foreground.xml, 108 x 108 viewport.
PAGES = ("M53,58 C47,54 40,53 32,54 L32,74 C40,73 47,74 53,78 Z "
         "M55,58 C61,54 68,53 76,54 L76,74 C68,73 61,74 55,78 Z")
BUBBLES = [(54, 49, 3.2), (49, 40, 2.2), (57, 33, 1.6)]
BG, PAPER, AMBER = "#2E4A3B", "#E8E2D0", "#D9A441"
# The site's ink (site/index.html --ink, light and dark).
INK_LIGHT, INK_DARK = "#1f2a22", "#e8e2d4"


def wordmark(font_path):
    font = TTFont(font_path)
    glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    pen, bounds = SVGPathPen(glyphs), BoundsPen(glyphs)
    x = 0
    for ch in "Terpoir":
        name = cmap[ord(ch)]
        # Font units are y-up; SVG is y-down, with the baseline at y = 0.
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        glyphs[name].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
        x += hmtx[name][0]
    cap = BoundsPen(glyphs)
    glyphs[cmap[ord("T")]].draw(cap)
    return pen.getCommands(), bounds.bounds, cap.bounds[3], font["head"].unitsPerEm


def logo(font_path):
    # As in render.py's feature graphic: the pages as tall as the capitals,
    # their bottom edge on the baseline, a 34/130 em gap, then the word.
    path, (left, top_ink, right, bottom), cap, upm = wordmark(font_path)
    s = cap / 25                      # pages: y 53..78
    book_w = 44 * s                   # pages: x 32..76
    gap = 34 / 130 * upm
    def pt(x, y):
        return f"{(x - 32) * s:.0f},{(y - 78) * s:.0f}"
    pages = re.sub(r"(\d+(?:\.\d+)?),(\d+(?:\.\d+)?)",
                   lambda m: pt(float(m.group(1)), float(m.group(2))), PAGES)
    circles = "".join(f'<circle cx="{(x - 32) * s:.0f}" cy="{(y - 78) * s:.0f}" r="{r * s:.0f}"/>'
                      for x, y, r in BUBBLES)
    top = -(78 - 31.4) * s            # the top bubble
    pad = 40
    width = book_w + gap + (right - left)
    view = f"{-pad} {top - pad:.0f} {width + 2 * pad:.0f} {bottom - top + 2 * pad:.0f}"
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}">\n'
            f"<title>Terpoir</title>\n"
            f"<style>.ink{{fill:{INK_LIGHT}}}@media (prefers-color-scheme:dark){{.ink{{fill:{INK_DARK}}}}}</style>\n"
            f'<path class="ink" d="{pages}"/>\n'
            f'<g fill="{AMBER}">{circles}</g>\n'
            f'<path class="ink" transform="translate({book_w + gap - left:.0f} 0)" d="{path}"/>\n'
            "</svg>\n")


def favicon():
    circles = "".join(f'<circle cx="{x}" cy="{y}" r="{r}"/>' for x, y, r in BUBBLES)
    return (HEADER + '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">\n'
            "<title>Terpoir</title>\n"
            f'<rect x="18" y="18" width="72" height="72" rx="16" fill="{BG}"/>\n'
            f'<path fill="{PAPER}" d="{PAGES}"/>\n'
            f'<g fill="{AMBER}">{circles}</g>\n'
            "</svg>\n")


out, font_path = sys.argv[1], sys.argv[2]
with open(out + "/logo.svg", "w") as f:
    f.write(logo(font_path))
with open(out + "/favicon.svg", "w") as f:
    f.write(favicon())
icon = Image.open(sys.argv[0].rsplit("/", 1)[0] + "/icon-512.png").convert("RGB")
icon.resize((180, 180), Image.LANCZOS).save(out + "/apple-touch-icon.png", optimize=True)
icon.save(out + "/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
